def run_pipeline(stage, centerline, volume, outdir):
    # These stages reproduce the order in Resample_Run_Unsteady_alt.py.
    c = stage('01_preclean_input', lambda: _clean(centerline, 0.0))
    c = stage('02_resample_centerline', lambda: _stage_execute('Resample', 'pf1', [c], {}), True)
    c = stage('03_clean_resampled_graph', lambda: _clean(c, 0.0))
    c = stage('04_generation', lambda: _stage_execute('Resample', 'pf2', [c], {}))
    c = stage('05_blanking', lambda: _stage_execute('Resample', 'pf3', [c], {}))
    c = stage('06_inlet_outlet_length', lambda: _stage_execute('Resample', 'pf4', [c], {}))
    c = stage('07_pressure_mmHg', lambda: _calculate_pressure_mmHg(c))
    c = stage('08_integrate_flow', lambda: _stage_execute('Resample', 'pf5', [_multiblock(c, volume)], {}), True)
    c = stage('09_power_ohms_law', lambda: _stage_execute('Resample', 'pf6', [c], {}))
    c = stage('10_poiseuille_resistance', lambda: _stage_execute('Resample', 'pf7', [_multiblock(c, volume)], {}))
    names = {8: '11_segment_metrics', 9: '12_sidedness',
             10: '13_rename_arrays', 11: '14_FFR',
             12: '15_segment_flow_power', 13: '16_remove_old_arrays',
             14: '17_threshold_FFR_08', 15: '18_threshold_FFR_09',
             16: '19_threshold_power', 17: '20_threshold_overlap'}
    for i in range(8, 18):
        c = stage(names[i], lambda i=i, c=c: _stage_execute('Resample', 'pf'+str(i), [c], {}),
                  i in (8, 11, 17))
    return c


def _calculate_pressure_mmHg(poly):
    # ParaView Calculator(Function='Pressure_average / 1333.22')
    from vtkmodules.util import numpy_support as ns
    p = poly.GetPointData().GetArray('Pressure_average')
    if p is None:
        raise RuntimeError("'Pressure_average' missing on WALT output; unable to calculate Pressure (mmHg).")
    result = vtk.vtkPolyData()
    result.DeepCopy(poly)
    scaled = ns.vtk_to_numpy(p).astype(np.float64,copy=True) / 1333.22
    arr = ns.numpy_to_vtk(np.ascontiguousarray(scaled), deep=1)
    arr.SetName('Pressure (mmHg)')
    result.GetPointData().RemoveArray('Pressure (mmHg)')
    result.GetPointData().AddArray(arr)
    return result

