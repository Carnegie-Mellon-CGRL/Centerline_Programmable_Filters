class _FilterContext:
    def __init__(self, inputs, output):
        self._inputs = list(inputs)
        self._out = output

    def GetInput(self):
        return self._inputs[0]

    def GetInputDataObject(self, port, connection):
        if port != 0:
            raise IndexError("Only input port zero is supported")
        return self._inputs[int(connection)]

    def GetOutput(self):
        return self._out

    def GetOutputDataObject(self, port=0):
        if port != 0:
            raise IndexError("Only output port zero is supported")
        return self._out


def _multiblock(*datasets):
    group = vtk.vtkMultiBlockDataSet()
    group.SetNumberOfBlocks(len(datasets))
    for i, ds in enumerate(datasets):
        group.SetBlock(i, ds)
    return group


def _stage_execute(label, key, inputs, overrides):
    if key not in STAGE_SCRIPTS:
        raise KeyError("Missing internal filter script: "+key)
    script = STAGE_SCRIPTS[key]
    # Allow changing sampling resolution without changing the mathematical code.
    for original, replacement in overrides.items():
        if original in script:
            script = script.replace(original, replacement)
    output = vtk.vtkPolyData()
    context = _FilterContext(inputs, output)
    env = {'self': context, 'output': output, 'inputs': inputs,
           '__name__': '__standalone_filter__', '__builtins__': __builtins__}
    exec(compile(script, label+'_'+key+'.py', 'exec'), env, env)
    if output.GetNumberOfPoints() == 0:
        raise RuntimeError('Stage '+label+' returned no points')
    return output


def _read_vtp(path):
    r=vtk.vtkXMLPolyDataReader()
    r.SetFileName(str(path));r.Update()
    out=vtk.vtkPolyData()
    out.ShallowCopy(r.GetOutput())
    if out.GetNumberOfPoints()==0:
        raise ValueError('Empty or unreadable centerline/surface VTP: '+str(path))
    return out


def _read_vtu(path):
    r=vtk.vtkXMLUnstructuredGridReader()
    r.SetFileName(str(path));r.Update()
    out=vtk.vtkUnstructuredGrid()
    out.ShallowCopy(r.GetOutput())
    if out.GetNumberOfCells()==0:
        raise ValueError('Empty or unreadable results VTU: '+str(path))
    return out


def _clean(src, tol=0.0):
    f=vtk.vtkCleanPolyData();f.SetInputData(src)
    f.PointMergingOn()
    f.ToleranceIsAbsoluteOff()
    f.SetTolerance(float(tol))
    f.ConvertLinesToPointsOff()
    f.ConvertPolysToLinesOff()
    f.ConvertStripsToPolysOff()
    f.Update()
    out=vtk.vtkPolyData();out.ShallowCopy(f.GetOutput())
    return out


def _probe(centerlines, volume):
    f=vtk.vtkProbeFilter()
    f.SetInputData(centerlines)
    f.SetSourceData(volume)
    f.Update()
    result=vtk.vtkPolyData();result.ShallowCopy(f.GetOutput())
    return result


def _cell_to_point(src):
    f=vtk.vtkCellDataToPointData();f.SetInputData(src);f.PassCellDataOn();f.Update()
    result=vtk.vtkPolyData();result.ShallowCopy(f.GetOutput())
    return result


def _save_poly(path, poly):
    path=Path(path)
    path.parent.mkdir(parents=True,exist_ok=True)
    temp=path.with_name(path.stem+'.writing.vtp')
    writer=vtk.vtkXMLPolyDataWriter()
    writer.SetFileName(str(temp))
    writer.SetInputData(poly)
    writer.SetDataModeToAppended()
    writer.SetCompressorTypeToZLib()
    if hasattr(writer,'SetCompressionLevel'):
        writer.SetCompressionLevel(3)
    if writer.Write()!=1:
        raise RuntimeError('Unable to write '+str(path))
    os.replace(temp,path)
    return str(path)


def _array_names(poly):
    p=poly.GetPointData()
    return [p.GetArrayName(i) for i in range(p.GetNumberOfArrays())]


