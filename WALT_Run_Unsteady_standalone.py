def main():
    args = _parse_args()
    if not args.centerlines or not args.vtu:
        raise SystemExit('Set CENTERLINES_PATH and VTU_PATH near top of file or pass --centerlines / --vtu.')
    cl_path = Path(args.centerlines).expanduser().resolve()
    vtu_path = Path(args.vtu).expanduser().resolve()
    for p in (cl_path,vtu_path):
        if not p.is_file():
            raise SystemExit('Missing input file: '+str(p))
    outdir = (Path(args.output_dir).expanduser().resolve() if args.output_dir
              else (cl_path.parent if cl_path.parent.name=='centerline_results'
                    else cl_path.parent/'centerline_results'))
    outdir.mkdir(parents=True,exist_ok=True)
    prefix = KIND
    report_path = outdir/(prefix+'_progress.json')
    report = {'pipeline':KIND, 'version':'unsteady_temporal_average_standalone',
              'started_utc':datetime.now(timezone.utc).isoformat(),
              'vtk_version':vtk.vtkVersion.GetVTKVersion(),
              'numpy_version':np.__version__,
              'inputs': {'centerlines':str(cl_path),'vtu':str(vtu_path)},
              'status':'running','settings':vars(args),'stages':[]}
    def persist():
        temp = report_path.with_suffix('.tmp')
        temp.write_text(json.dumps(report,indent=2,default=str),encoding='utf-8')
        os.replace(temp,report_path)
    persist()
    index=0
    t0=time.perf_counter()
    def stage(name, runner, important=False):
        nonlocal index
        index+=1
        start=time.perf_counter()
        print(f'[{prefix}] {index:02d} {name} START',flush=True)
        record={'index':index,'name':name,'status':'running'}
        report['stages'].append(record)
        persist()
        try:
            result=runner()
            if not isinstance(result, vtk.vtkPolyData):
                raise TypeError('Stage '+name+' returned '+repr(type(result)))
            if result.GetNumberOfPoints()==0:
                raise RuntimeError('Stage '+name+' returned zero centerline points')
            record.update({'status':'completed',
                           'seconds':round(time.perf_counter()-start,3),
                           'points':result.GetNumberOfPoints(),
                           'cells':result.GetNumberOfCells(),
                           'point_arrays':_array_names(result)})
            if important or not args.no_stage_files:
                filename=f'{prefix}_{index:02d}_{name}.vtp'
                record['file']=_save_poly(outdir/filename,result)
            persist()
            print(f'[{prefix}] {index:02d} {name} COMPLETE  '
                  f'({result.GetNumberOfPoints()} points, {record["seconds"]:.1f} s)',flush=True)
            return result
        except BaseException as exc:
            record.update({'status':'FAILED',
                           'seconds':round(time.perf_counter()-start,3),
                           'error':str(exc),'traceback':traceback.format_exc()})
            report['status']='failed'
            report['last_successful_stage']=index-1
            persist()
            print(f'[{prefix}] Stage FAILED; previous files retained in {outdir}',flush=True)
            raise
    try:
        print(f'[{prefix}] Input centerline: {cl_path}',flush=True)
        print(f'[{prefix}] Input VTU: {vtu_path}',flush=True)
        cl=_read_vtp(cl_path)
        vol=_read_vtu(vtu_path)
        final=run_pipeline(stage,cl,vol,outdir)
        final_path=outdir/(prefix+'_centerlines_final.vtp')
        _save_poly(final_path,final)
        report.update({'status':'complete','final_output':str(final_path),
                       'total_seconds':round(time.perf_counter()-t0,3),
                       'finished_utc':datetime.now(timezone.utc).isoformat()})
        persist()
        print(f'[{prefix}] ALL DONE: {final_path}',flush=True)
    except BaseException as exc:
        if report['status']!='failed':
            report['status']='failed'
            report['error']=str(exc)
            persist()
        raise

if __name__=='__main__':
    main()
